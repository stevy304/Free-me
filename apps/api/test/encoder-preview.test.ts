import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Logger } from '@nestjs/common';
import request from 'supertest';
import { makeApp, resetDb, signIn, WEB } from './helpers';
import { Billing } from '../src/billing/billing';
import { STORAGE } from '../src/media/queue';
import { LocalStorage } from '../src/media/storage';
import { LiveSync, endLive, finishLive, privateLivePrefix } from '../src/live/sync';
import { sampleIngest } from '../src/live/ingest-health';
import { beginEncoderPublication } from '../src/live/encoder-publication';
import { encoderPlaylist } from '../src/live/encoder-playlist';

const dir = mkdtempSync(join(tmpdir(), 'freeme-private-live-'));
let ctx: Awaited<ReturnType<typeof makeApp>>;
const secret = 'preview-secret-0123456789abcdef';
beforeAll(async () => { ctx = await makeApp({ redis: false, storageDir: join(dir, 'storage'), env: { LIVE_RTMP_URL: 'rtmps://encoder.example/live', LIVE_RTMP_SECRET: secret } }); });
beforeEach(async () => { await resetDb(ctx.prisma); await ctx.clearLimits(); });
afterAll(async () => { await ctx.app.close(); rmSync(dir, { recursive: true, force: true }); });

it('keeps real rehearsal media private and excludes it from public playback and replay', async () => {
  const owner = await signIn(ctx.http, ctx.mail, 'preview-host@example.com');
  await owner.agent.post('/api/channels').set('Origin', WEB).send({ handle: 'preview-host', name: 'Preview Host' }).expect(201);
  const fan = await signIn(ctx.http, ctx.mail, 'preview-fan@example.com');
  await fan.agent.post('/api/channels/preview-host/follow').set('Origin', WEB).expect(200);
  const user = await ctx.prisma.user.findUniqueOrThrow({ where: { email: 'preview-host@example.com' } });
  await new Billing(ctx.prisma as never, ctx.config).grantPremium(user.id, 1);
  const { stream, encoder } = (await owner.agent.get('/api/hub/live')).body;
  const folder = mkdtempSync(join(dir, 'hls-'));
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc2=size=640x360:rate=30', '-f', 'lavfi', '-i', 'sine=frequency=440', '-t', '6', '-c:v', 'libx264', '-preset', 'ultrafast', '-c:a', 'aac', '-force_key_frames', 'expr:gte(t,n_forced*1)', '-sc_threshold', '0', '-f', 'hls', '-hls_time', '1', '-hls_list_size', '0', '-hls_segment_filename', join(folder, '%d.ts'), join(folder, 'index.m3u8')]);
  const full = readFileSync(join(folder, 'index.m3u8'), 'utf8');
  const parsed = encoderPlaylist(full);
  expect(parsed.segments).toHaveLength(6);
  const rehearsal = [...parsed.headers, '#EXT-X-MEDIA-SEQUENCE:0', ...parsed.segments.slice(0, 2).flatMap((s) => [...s.tags, s.name])].join('\n') + '\n';
  writeFileSync(join(folder, 'index.m3u8'), rehearsal);
  const storage = ctx.app.get<LocalStorage>(STORAGE);
  const sync = new LiveSync(storage, stream.id, folder);
  await request(ctx.http).post(`/api/live/rtmp/publish?secret=${secret}`).type('form').send({ name: encoder.streamKey, clientid: '1', flashver: 'FMLE/3.0' }).expect(302);
  await sync.tick();
  const health = await sampleIngest(folder, 'ffprobe');
  expect(health).toMatchObject({ width: 640, height: 360, fps: 30, hasAudio: true, videoCodec: 'h264', audioCodec: 'aac' });
  expect(health!.deliveredKbps).toBeGreaterThan(0);
  await ctx.prisma.liveStream.update({ where: { id: stream.id }, data: { ingestHealth: health as any, replayVisibility: 'PUBLIC' } });
  await request(ctx.http).get(`/api/hub/live/${stream.id}/preview`).expect(401);
  await fan.agent.get(`/api/hub/live/${stream.id}/preview`).expect(404);
  const preview = await owner.agent.get(`/api/hub/live/${stream.id}/preview`).expect(200);
  expect(preview.headers['cache-control']).toBe('private, no-store');
  expect(preview.text).toContain('/api/storage/local/file/');
  expect(await storage.list(`pub/live/${stream.id}/`)).toEqual([]);
  expect((await request(ctx.http).get('/api/live')).body.streams).toEqual([]);
  expect(await ctx.prisma.notification.count({ where: { liveStreamId: stream.id } })).toBe(0);
  await fan.agent.post('/api/hub/live/publish').set('Origin', WEB).send({}).expect(400);
  const published = await owner.agent.post('/api/hub/live/publish').set('Origin', WEB).send({}).expect(200);
  expect(published.body.stream.status).toBe('LIVE');
  expect(await ctx.prisma.notification.count({ where: { liveStreamId: stream.id } })).toBe(1);
  await owner.agent.post('/api/hub/live/publish').set('Origin', WEB).send({}).expect(400);
  const boundary = await beginEncoderPublication(ctx.prisma, stream.id, folder);
  expect(boundary).toBe(3); // The in-progress segment 2 is excluded too.
  writeFileSync(join(folder, 'index.m3u8'), full);
  sync.setPublicFrom(boundary); await sync.tick();
  const publicKeys = await storage.list(`pub/live/${stream.id}/`);
  expect(publicKeys).not.toContain(`pub/live/${stream.id}/0.ts`);
  expect(publicKeys).not.toContain(`pub/live/${stream.id}/1.ts`);
  expect(publicKeys).not.toContain(`pub/live/${stream.id}/2.ts`);
  expect(publicKeys).toContain(`pub/live/${stream.id}/3.ts`);
  const publicPlaylist = await storage.getText(`pub/live/${stream.id}/index.m3u8`);
  expect(encoderPlaylist(publicPlaylist!).segments.map((s) => s.name)).toEqual(['3.ts', '4.ts', '5.ts']);
  await request(ctx.http).get(`/api/storage/local/pub/live/${stream.id}/0.ts`).expect(404);
  await endLive(ctx.prisma, stream.id);
  await finishLive(ctx.prisma, storage, sync, async () => undefined, new Logger('preview-test'));
  const ended = await ctx.prisma.liveStream.findUniqueOrThrow({ where: { id: stream.id } });
  expect(ended.replayVideoId).toBeTruthy();
  const video = await ctx.prisma.video.findUniqueOrThrow({ where: { id: ended.replayVideoId! } });
  const duration = Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', storage.path(video.sourceFileS3Key!)], { encoding: 'utf8' }).trim());
  expect(duration).toBeGreaterThan(2.9); expect(duration).toBeLessThan(3.2);
  expect(await storage.list(privateLivePrefix(stream.id))).toEqual([]);
  await owner.agent.get(`/api/hub/live/${stream.id}/preview`).expect(404);
}, 60_000);

it('discards an ended private rehearsal without creating a replay, even with Public replay selected', async () => {
  const owner = await signIn(ctx.http, ctx.mail, 'cancel-preview@example.com');
  await owner.agent.post('/api/channels').set('Origin', WEB).send({ handle: 'cancel-preview', name: 'Rehearsal' }).expect(201);
  const user = await ctx.prisma.user.findUniqueOrThrow({ where: { email: 'cancel-preview@example.com' } });
  await new Billing(ctx.prisma as never, ctx.config).grantPremium(user.id, 1);
  const { stream, encoder } = (await owner.agent.get('/api/hub/live')).body;
  await request(ctx.http).post(`/api/live/rtmp/publish?secret=${secret}`).type('form').send({ name: encoder.streamKey }).expect(302);
  await ctx.prisma.liveStream.update({ where: { id: stream.id }, data: { replayVisibility: 'PUBLIC' } });
  const storage = ctx.app.get<LocalStorage>(STORAGE);
  await storage.putBuffer(privateLivePrefix(stream.id) + '0.ts', Buffer.from('private rehearsal'));
  await owner.agent.post('/api/hub/live/end').set('Origin', WEB).send({}).expect(200);
  const folder = mkdtempSync(join(dir, 'cancel-'));
  await finishLive(ctx.prisma, storage, new LiveSync(storage, stream.id, folder), async () => { throw new Error('Rehearsals must never enter the video queue.'); }, new Logger('preview-cancel-test'));
  expect(await ctx.prisma.video.count()).toBe(0);
  expect(await storage.list(privateLivePrefix(stream.id))).toEqual([]);
  expect(await ctx.prisma.liveStream.findUniqueOrThrow({ where: { id: stream.id } })).toMatchObject({ status: 'ENDED', startedAt: null, replayVideoId: null, finalizedAt: expect.any(Date) });
  await request(ctx.http).post(`/api/live/rtmp/publish?secret=${secret}`).type('form').send({ name: encoder.streamKey }).expect(403);
});
